// ── 섹션 분류 ───────────────────────────────────
export function classifyTechSection(
  sectionName: string
): "core_tech" | "rd_plan" | "product" | null {
  const name = sectionName.toLowerCase();

  if (
    name.includes("기술") ||
    name.includes("핵심") ||
    name.includes("혁신") ||
    name.includes("차별") ||
    name.includes("특허")
  ) {
    return "core_tech";
  }

  if (
    name.includes("r&d") ||
    name.includes("연구") ||
    name.includes("개발계획") ||
    name.includes("로드맵") ||
    name.includes("개발 계획")
  ) {
    return "rd_plan";
  }

  if (
    name.includes("제품") ||
    name.includes("서비스") ||
    name.includes("솔루션") ||
    name.includes("플랫폼")
  ) {
    return "product";
  }

  return null;
}

