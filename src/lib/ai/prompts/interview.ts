/**
 * 대화 내용에서 팀 역량 수준을 자동 판별
 */
function detectTeamMaturity(
  previousQA: { question: string; answer: string }[]
): "early" | "growth" | "tech" | "unknown" {
  if (previousQA.length === 0) return "unknown";

  const allAnswers = previousQA.map((qa) => qa.answer).join(" ");
  const lower = allAnswers.toLowerCase();

  // 매출 추정
  const revenueMatch = allAnswers.match(/(\d+)\s*억/);
  const revenue = revenueMatch ? parseInt(revenueMatch[1]) : 0;

  // 직원 수 추정
  const empMatch = allAnswers.match(/(\d+)\s*명/);
  const employees = empMatch ? parseInt(empMatch[1]) : 0;

  // 특허 추정
  const patentMatch = allAnswers.match(/특허\s*(\d+)/);
  const patents = patentMatch ? parseInt(patentMatch[1]) : 0;

  // 기술집약형 판별
  if (patents >= 3 || lower.includes("r&d") || lower.includes("연구개발") || lower.includes("기술기반")) {
    return "tech";
  }

  // 성장/성숙팀 판별
  if (revenue >= 5 || employees >= 10) {
    return "growth";
  }

  // 초기팀 판별 (매출 적거나 설립 초기 언급)
  if (
    revenue < 5 ||
    employees < 5 ||
    lower.includes("예비창업") ||
    lower.includes("초기") ||
    lower.includes("아직") ||
    lower.includes("준비중") ||
    lower.includes("시작")
  ) {
    return "early";
  }

  return "unknown";
}

