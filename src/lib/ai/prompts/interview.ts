// 7. 추가 인터뷰 (보완 질문) 프롬프트 (신규)
// ========================================
export function buildSupplementaryQuestionPrompt(
  missingData: string[],
  previousQA: { question: string; answer: string }[]
): string {
  const teamMaturity = detectTeamMaturity(previousQA);
  const maturityHint = teamMaturity === "early"
    ? "초기팀이므로 비전/가능성 관점에서 질문하세요."
    : teamMaturity === "growth"
      ? "성장팀이므로 실적/확장 관점에서 질문하세요."
      : teamMaturity === "tech"
        ? "기술집약팀이므로 기술 우위/혁신성 관점에서 질문하세요."
        : "";

  return `대표님의 사업 프로필에서 다음 데이터가 부족합니다:
${missingData.map((d) => `- ${d}`).join("\n")}

## 지금까지 대화
${previousQA.map((qa) => `Q: ${qa.question}\nA: ${qa.answer}`).join("\n\n")}

## 규칙
1. 부족한 데이터 중 가장 중요한 것 하나에 대해 질문
2. **정부정책/트렌드를 먼저 언급**하고 맥락에서 질문 (합격률 향상)
3. 이전에 했던 질문과 겹치지 않게
4. **100자 이내**로 간결하게 (보기를 제시하여 답변 부담 줄이기)
5. 어려운 용어는 풀어서 설명
${maturityHint ? `6. ${maturityHint}` : ""}

질문만 출력하세요.`;
}
